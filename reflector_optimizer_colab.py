def half_power_angle(angles, eff):
    """First angle at which capture drops below half of its value at angles[0]. Linear interpolation."""
    eff = np.asarray(eff); angles = np.asarray(angles)
    if eff[0] <= 0:
        return np.nan
    rel = eff / eff[0]
    below = np.where(rel < 0.5)[0]
    if len(below) == 0:
        return np.nan                       # never reaches -3 dB inside the swept range
    i = below[0]
    a0, a1, r0, r1 = angles[i-1], angles[i], rel[i-1], rel[i]
    return a0 + (0.5 - r0) * (a1 - a0) / (r1 - r0)

