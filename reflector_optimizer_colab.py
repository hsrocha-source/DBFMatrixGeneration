def export_reflector_to_stl(params, F, D, filename="shaped_reflector.stl"):
    print(f"Generating STL mesh for F={F:.2f}m, D={D:.2f}m...")

    # 1. Generate a Cartesian Grid masked to a circle for uniform triangulation
    num_r = 200
    num_theta = 600 # Higher angular resolution for smooth curved edges
    r = np.linspace(0, D / 2.0, num_r)
    theta = np.linspace(0, 2 * np.pi, num_theta)
    R, Theta = np.meshgrid(r, theta)

    x_grid_raw = np.round((R * np.cos(Theta)).flatten(), decimals=6)
    y_grid_raw = np.round((R * np.sin(Theta)).flatten(), decimals=6)

    # Stack and filter out duplicate origin and overlapping 2*pi points
    points2D = np.unique(np.vstack([x_grid_raw, y_grid_raw]).T, axis=0)

    x_grid = points2D[:, 0]
    y_grid = points2D[:, 1]

    # 2. Evaluate Z-heights safely with JAX
    z_grid = np.array(reflector_surface(jnp.array(x_grid), jnp.array(y_grid), params, F))

    # 3. Triangulate the 2D coordinates
    tri = Delaunay(points2D)

    # 4. Construct the 3D STL mesh
    points3D = np.vstack([x_grid, y_grid, z_grid]).T
    reflector_mesh = mesh.Mesh(np.zeros(tri.simplices.shape[0], dtype=mesh.Mesh.dtype))

    reflector_mesh.vectors = points3D[tri.simplices]

    # Calculate face normals for EM solvers/manufacturing
    reflector_mesh.update_normals()

    if np.mean(reflector_mesh.normals[:, 2]) < 0:
        reflector_mesh.vectors = reflector_mesh.vectors[:, [0, 2, 1], :]
        reflector_mesh.update_normals()

    reflector_mesh.translate([X_OFFSET, Y_OFFSET, 0.0])
    # 5. Save the file
    reflector_mesh.save(filename)
    print(f"Success! Exported to '{filename}' with {len(tri.simplices)} triangular facets.")

