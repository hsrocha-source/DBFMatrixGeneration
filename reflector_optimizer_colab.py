def az_3db_point(params, F, el_deg, az_max=6.0, n=13, pol='x'):
    """Azimuth angle where PO capture efficiency falls to half its az=0 value, at fixed elevation."""
    az = np.linspace(0.0, az_max, n)
    res = run_po_check(params, F, [(a, el_deg) for a in az], pols=(pol,), plot_pol=None)
    eff = np.array([r['eff'] for r in res])
    rel = eff / eff[0]

    below = np.where(rel < 0.5)[0]
    if len(below) == 0:
        print(f"el = {el_deg:.0f} deg: still at {100*rel[-1]:.0f}% of boresight at az = {az_max:.1f} deg, no -3 dB crossing in range")
        return None, az, rel
    i = below[0]
    a3 = np.interp(0.5, [rel[i], rel[i-1]], [az[i], az[i-1]])   # rel is decreasing, so reverse for np.interp
    print(f"el = {el_deg:.0f} deg: -3 dB in azimuth at {a3:.2f} deg "
          f"(absolute eff there = {100*eff[0]*0.5:.1f}%, vs {100*eff[0]:.1f}% at az=0)")
    return a3, az, rel

