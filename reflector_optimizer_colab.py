import numpy as np
import matplotlib.pyplot as plt

# TPU runs dot_general in bfloat16 by default. The incident phase k0*(p.d) needs full float32,
# so force it globally before anything is jitted.
jax.config.update("jax_default_matmul_precision", "highest")

# ---------------- PO settings ----------------
freq_hz            = 1315e6
c0                 = 299792458.0
lam                = c0 / freq_hz
k0                 = 2.0 * np.pi / lam
eta0               = 376.730313668
po_samples_per_lam = 4        # surface sampling on the projected aperture. Re-run with 6 to confirm convergence.
po_chunk           = 2048     # surface points per chunk. Memory ~ chunk * N_elem * 3 * 8 B * (a few)

N_ELEM_X = int(round(array_size_x / element_pitch))
N_ELEM_Y = int(round(array_size_y / element_pitch))

TWO_PI = 2.0 * np.pi

def wrap_phase(ph):
    """Reduce a large phase to [-pi, pi] before exp(). Helps TPU transcendentals, costs nothing."""
    return ph - TWO_PI * jnp.round(ph / TWO_PI)

# ---------------- geometry (same conventions as trace_ray) ----------------
def array_frame(params, F):
    z_center = reflector_surface(X_OFFSET, Y_OFFSET, params, F)
    v_chief  = jnp.array([-X_OFFSET, -Y_OFFSET, -z_center])
    n_arr    = v_chief / jnp.linalg.norm(v_chief)          # reflector centre -> array
    u_tmp    = jnp.array([1.0, 0.0, 0.0])
    u_vec    = u_tmp - jnp.dot(u_tmp, n_arr) * n_arr
    u_vec    = u_vec / jnp.linalg.norm(u_vec)
    v_vec    = jnp.cross(n_arr, u_vec)
    return n_arr, u_vec, v_vec

def element_positions(u_vec, v_vec):
    xi = (jnp.arange(N_ELEM_X) - (N_ELEM_X - 1) / 2.0) * element_pitch
    yi = (jnp.arange(N_ELEM_Y) - (N_ELEM_Y - 1) / 2.0) * element_pitch
    XI, YI = jnp.meshgrid(xi, yi, indexing='xy')           # (Ny, Nx)
    r = XI[..., None] * u_vec + YI[..., None] * v_vec       # array plane passes through the origin
    return r.reshape(-1, 3), XI, YI

def po_surface_grid():
    # Cell-centred (midpoint) sampling: samples sit at (i + 0.5) * h from the aperture
    # edge, so the grid never lands on the aperture centre, where the autodiff gradient
    # of the surface is 0/0. dA is then exactly the cell area (proper midpoint rule).
    h  = lam / po_samples_per_lam
    n  = int(np.ceil(D / h))
    h  = D / n
    xs = X_OFFSET - D/2 + (np.arange(n) + 0.5) * h
    ys = Y_OFFSET - D/2 + (np.arange(n) + 0.5) * h
    dA = h * h
    X, Y = np.meshgrid(xs, ys)
    inside = ((X - X_OFFSET)**2 + (Y - Y_OFFSET)**2) <= (D/2)**2
    x = X[inside].ravel(); y = Y[inside].ravel()
    w = np.full(x.shape, dA)
    n_real = len(x)
    pad = (-n_real) % po_chunk
    # Pad by repeating a real in-aperture sample with zero weight. 0 * NaN is still NaN,
    # so the padding must be placed where the surface and its gradient are finite.
    x = np.concatenate([x, np.full(pad, x[0])])
    y = np.concatenate([y, np.full(pad, y[0])])
    w = np.concatenate([w, np.zeros(pad)])
    f32 = lambda a: jnp.asarray(a, dtype=jnp.float32)
    return f32(x), f32(y), f32(w), dA, n_real

def incident_direction(az_deg, el_deg):
    az = jnp.deg2rad(az_deg); el = jnp.deg2rad(el_deg)
    u = jnp.sin(az); v = jnp.sin(el)
    w = -jnp.sqrt(jnp.maximum(1.0 - u**2 - v**2, 1e-12))
    return jnp.array([u, v, w], dtype=jnp.float32)

def pol_vectors(d):
    xhat = jnp.array([1.0, 0.0, 0.0], dtype=jnp.float32)
    px = xhat - jnp.dot(xhat, d) * d
    px = px / jnp.linalg.norm(px)
    py = jnp.cross(px, d)                                   # equals +y at boresight
    return px, py

# ---------------- PO forward model ----------------
_surf_z    = jax.vmap(reflector_surface, in_axes=(0, 0, None, None))
_surf_grad = jax.vmap(jax.grad(reflector_surface, argnums=(0, 1)), in_axes=(0, 0, None, None))

@jax.jit
def po_fields_at_elements(params, F, d, pol, xs, ys, ws):
    """Scattered E and H (V/m, A/m) at every element centre for a unit-amplitude
    plane wave travelling along d with polarization pol. Time convention exp(+j w t)."""
    n_arr, u_vec, v_vec = array_frame(params, F)
    r_elem, _, _ = element_positions(u_vec, v_vec)          # (Ne, 3)

    def chunk_contribution(chunk):
        x, y, w = chunk
        z      = _surf_z(x, y, params, F)
        zx, zy = _surf_grad(x, y, params, F)
        p      = jnp.stack([x, y, z], axis=-1)                                   # (n, 3)
        ndS    = jnp.stack([-zx, -zy, jnp.ones_like(zx)], axis=-1) * w[:, None]  # n_hat * dS, no sqrt needed

        # Illumination mask: front face sees the wave, and the incoming ray does not pass through the array plate
        lit     = jnp.sum(ndS * d, axis=-1) < 0.0
        t_in    = jnp.sum(p * n_arr, axis=-1) / jnp.dot(d, n_arr)
        p_blk   = p - t_in[:, None] * d
        blocked = (jnp.abs(jnp.sum(p_blk * u_vec, axis=-1)) < array_size_x / 2) & \
                  (jnp.abs(jnp.sum(p_blk * v_vec, axis=-1)) < array_size_y / 2)
        mask    = jnp.logical_and(lit, jnp.logical_not(blocked)).astype(p.dtype)

        # Incident plane wave and PO current  J_s = 2 n x H_inc  on the lit side
        kp    = wrap_phase(k0 * jnp.sum(p * d, axis=-1))
        E_inc = pol[None, :] * jnp.exp(-1j * kp)[:, None]
        H_inc = jnp.cross(d[None, :], E_inc) / eta0
        JdS   = 2.0 * jnp.cross(ndS, H_inc) * mask[:, None]                      # (n, 3), units A*m

        # Exact free-space field of each current element at each observation point
        Rv  = r_elem[None, :, :] - p[:, None, :]                                 # (n, Ne, 3)
        R   = jnp.sqrt(jnp.sum(Rv * Rv, axis=-1))                                # (n, Ne)
        Rh  = Rv / R[..., None]
        g   = jnp.exp(-1j * wrap_phase(k0 * R))
        JdR = jnp.sum(JdS[:, None, :] * Rh, axis=-1)
        Jn  = JdS[:, None, :]
        trans = Jn - JdR[..., None] * Rh
        longi = 3.0 * JdR[..., None] * Rh - Jn
        E = (-1j * eta0 / (4.0 * jnp.pi * k0)) * g[..., None] * (
                k0**2 * trans / R[..., None]
              + longi * (1.0 / R**3 + 1j * k0 / R**2)[..., None])
        H = (1j * k0 / (4.0 * jnp.pi)) * (g * (1.0 + 1.0 / (1j * k0 * R)) / R)[..., None] * jnp.cross(Jn, Rh)
        return jnp.sum(E, axis=0), jnp.sum(H, axis=0)                           # (Ne, 3) each

    xs_c = xs.reshape(-1, po_chunk); ys_c = ys.reshape(-1, po_chunk); ws_c = ws.reshape(-1, po_chunk)
    E_ch, H_ch = jax.lax.map(chunk_contribution, (xs_c, ys_c, ws_c))
    return jnp.sum(E_ch, axis=0), jnp.sum(H_ch, axis=0), n_arr, u_vec, v_vec

# ---------------- metrics ----------------
def po_metrics(E, H, n_arr, u_vec, v_vec, d, copol_is_u):
    # Explicit sum-products instead of complex @ : complex dot_general is not reliably supported on TPU
    Eu = jnp.sum(E * u_vec, axis=-1)
    Ev = jnp.sum(E * v_vec, axis=-1)

    # Power flowing through each element cell toward the array (Poynting flux * cell area)
    Sn     = jnp.sum(0.5 * jnp.real(jnp.cross(E, jnp.conj(H))) * n_arr, axis=-1)
    P_cap  = jnp.sum(Sn) * element_pitch**2
    P_inc  = (1.0 / (2.0 * eta0)) * jnp.pi * (D / 2)**2 * jnp.abs(d[2])        # unit-amplitude plane wave on the projected aperture
    eff    = float(P_cap / P_inc)

    Eco = (Eu if copol_is_u else Ev).reshape(N_ELEM_Y, N_ELEM_X)
    Ecx = (Ev if copol_is_u else Eu).reshape(N_ELEM_Y, N_ELEM_X)
    P2  = jnp.abs(Eco)**2 + jnp.abs(Ecx)**2
    xpol = float(jnp.sum(jnp.abs(Ecx)**2) / jnp.sum(P2))

    _, XI, YI = element_positions(u_vec, v_vec)
    cx = float(jnp.sum(XI * P2) / jnp.sum(P2)); cy = float(jnp.sum(YI * P2) / jnp.sum(P2))

    # Adjacent-element phase step of the co-pol field, only where the field is within 20 dB of its peak
    amp = jnp.abs(Eco); strong = amp > 0.1 * jnp.max(amp)
    dphx = jnp.abs(jnp.angle(Eco[:, 1:] * jnp.conj(Eco[:, :-1]))); mx = strong[:, 1:] & strong[:, :-1]
    dphy = jnp.abs(jnp.angle(Eco[1:, :] * jnp.conj(Eco[:-1, :]))); my = strong[1:, :] & strong[:-1, :]
    dph_max = float(jnp.maximum(jnp.max(jnp.where(mx, dphx, 0.0)), jnp.max(jnp.where(my, dphy, 0.0)))) / TWO_PI

    return dict(eff=eff, xpol=xpol, cx=cx, cy=cy, dph_max=dph_max, Eco=np.array(Eco))

# ---------------- driver ----------------
