def trace_ray_arrival(x, y, theta_az_deg, theta_el_deg, params, F):
    """Same geometry as trace_ray, hard masks, plus the arrival angle at the array plane."""
    az = theta_az_deg * jnp.pi / 180.0
    el = theta_el_deg * jnp.pi / 180.0
    z_surf = reflector_surface(x, y, params, F)
    p_surf = jnp.array([x, y, z_surf])
    u = jnp.sin(az); v = jnp.sin(el)
    w = -jnp.sqrt(jnp.maximum(1.0 - u**2 - v**2, 1e-8))
    d_in = jnp.array([u, v, w])
    n_surf = get_normal(x, y, params, F)
    d_out = d_in - 2.0 * jnp.dot(d_in, n_surf) * n_surf

    z_center = reflector_surface(X_OFFSET, Y_OFFSET, params, F)
    v_chief = jnp.array([-X_OFFSET, -Y_OFFSET, -z_center])
    n_arr = v_chief / jnp.linalg.norm(v_chief)
    u_tmp = jnp.array([1.0, 0.0, 0.0])
    u_vec = u_tmp - jnp.dot(u_tmp, n_arr) * n_arr
    u_vec = u_vec / jnp.linalg.norm(u_vec)
    v_vec = jnp.cross(n_arr, u_vec)

    t_in = jnp.dot(p_surf, n_arr) / (jnp.dot(d_in, n_arr) + 1e-8)
    p_block = p_surf - t_in * d_in
    blocked = (jnp.abs(jnp.dot(p_block, u_vec)) < array_size_x / 2) & \
              (jnp.abs(jnp.dot(p_block, v_vec)) < array_size_y / 2)

    t_out = -jnp.dot(p_surf, n_arr) / (jnp.dot(d_out, n_arr) + 1e-8)
    p_hit = p_surf + t_out * d_out
    valid = jnp.logical_and(jnp.logical_not(blocked), t_out > 0.0)
    cos_arr = jnp.dot(d_out, n_arr)                         # cos of angle from array normal at arrival
    return jnp.dot(p_hit, u_vec), jnp.dot(p_hit, v_vec), cos_arr, valid

trace_arrival_vmap = jax.jit(jax.vmap(trace_ray_arrival, in_axes=(0, 0, 0, 0, None, None)))

def q_from_edge_level(theta_deg, level_db):
    """Exponent q of a cos^q(theta) power pattern that is level_db down at theta_deg."""
    return -level_db / (-10.0 * np.log10(np.cos(np.radians(theta_deg))))

def arrival_stats(params, F, az, el, x_ap, y_ap, theta_max=70.0, elem_pattern=None):
    x_hit, y_hit, cos_arr, valid = trace_arrival_vmap(
        x_ap, y_ap, jnp.full_like(x_ap, az), jnp.full_like(y_ap, el), params, F)
    x_hit, y_hit, cos_arr, valid = map(np.asarray, (x_hit, y_hit, cos_arr, valid))
    theta = np.degrees(np.arccos(np.clip(cos_arr, -1.0, 1.0)))
    captured = valid & (np.abs(x_hit) <= array_size_x / 2) & (np.abs(y_hit) <= array_size_y / 2)
    n_tot = len(x_ap)
    n_cap = captured.sum()
    inside = captured & (theta <= theta_max)
    w = elem_pattern(theta) if elem_pattern is not None else np.ones_like(theta)
    return dict(
        eff          = n_cap / n_tot,                       # what print_capture_efficiencies reports
        frac_out     = (captured & (theta > theta_max)).sum() / max(n_cap, 1),   # of the captured rays, share beyond theta_max
        eff_usable   = inside.sum() / n_tot,                # captured AND within theta_max
        eff_weighted = (w * captured).sum() / n_tot,        # captured, each ray weighted by the element power pattern
        theta_cap    = theta[captured],
        theta_95     = np.percentile(theta[captured], 95) if n_cap else np.nan,
    )

